mac("WrDiffMaxWhere", wr_diff_where)
mac("WrDiffDefaultOne", f"{wr_diff_default_one:.0e}".replace("e-0", r"\cdot10^{-").replace("e-", r"\cdot10^{-") + "}"
    if wr_diff_default_one > 0 else "0")

